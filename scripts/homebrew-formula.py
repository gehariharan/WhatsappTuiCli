#!/usr/bin/env python3
"""Generate Formula/whatsapp-axi.rb for the gehariharan/homebrew-tap repository.

    scripts/homebrew-formula.py VERSION SOURCE_SHA256 OUTPUT [--commit SHA]

SOURCE_SHA256 is the SHA-256 of GitHub's source tarball for tag vVERSION:
https://github.com/gehariharan/whatsapp-axi/archive/refs/tags/vVERSION.tar.gz

The formula builds from source with Homebrew's Go, so nothing downloaded is a
prebuilt macOS binary and Gatekeeper never quarantines it (whatsapp-axi is not
signed). This script only writes OUTPUT; publishing it to the tap is a
separate, manual step (docs/releasing.md).
"""
import argparse
from pathlib import Path
import re
import sys

REPO = "gehariharan/whatsapp-axi"
BUILDINFO = "github.com/gehariharan/whatsapp-axi/internal/buildinfo"
VERSION_RE = r"[0-9]+\.[0-9]+\.[0-9]+(?:-[A-Za-z0-9][A-Za-z0-9.-]*)?"


def render(version, source_sha256, commit=None):
    commit_flag = f"\n      -X {BUILDINFO}.Commit={commit}" if commit else ""
    return f'''# Generated by whatsapp-axi scripts/homebrew-formula.py for v{version}.
# Do not edit by hand; regenerate it for each release.
class WhatsappAxi < Formula
  desc "Agent-facing CLI that reads a local wasync WhatsApp archive"
  homepage "https://github.com/{REPO}"
  url "https://github.com/{REPO}/archive/refs/tags/v{version}.tar.gz"
  sha256 "{source_sha256}"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  depends_on "go" => :build

  def install
    ENV["CGO_ENABLED"] = "0"
    ldflags = %W[
      -s -w
      -X {BUILDINFO}.Version=#{{version}}{commit_flag}
      -X {BUILDINFO}.Date=#{{time.iso8601}}
    ]
    system "go", "build", *std_go_args(ldflags:), "./cmd/whatsapp-axi"
  end

  def caveats
    <<~EOS
      whatsapp-axi reads WhatsApp data only through wasync; install it with:
        brew install --cask gehariharan/tap/wasync
    EOS
  end

  test do
    assert_equal version.to_s, shell_output("#{{bin}}/whatsapp-axi --version").strip
  end
end
'''


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("version", help="release version without the leading v, e.g. 0.1.0")
    parser.add_argument("source_sha256", help="SHA-256 of the GitHub source tarball for tag vVERSION")
    parser.add_argument("output", help="where to write whatsapp-axi.rb")
    parser.add_argument("--commit", help="commit the tag points to (hex), embedded in `whatsapp-axi version`")
    args = parser.parse_args(argv)
    if not re.fullmatch(VERSION_RE, args.version):
        parser.error(f"invalid version {args.version!r} (expected e.g. 0.1.0 or 0.1.0-rc.1, no leading v)")
    if not re.fullmatch(r"[0-9a-f]{64}", args.source_sha256):
        parser.error("SOURCE_SHA256 must be 64 lowercase hex digits")
    if args.commit is not None and not re.fullmatch(r"[0-9a-f]{7,40}", args.commit):
        parser.error("--commit must be 7 to 40 lowercase hex digits")
    Path(args.output).write_text(render(args.version, args.source_sha256, args.commit), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
